#!/usr/bin/env python3
"""Generate the AppCache manifests from the files that actually exist.

Why this script exists (psx8-style hygiene):
  · A manifest entry that 404s breaks the whole cache install on the PS4
    browser, and a hand-kept manifest rots the moment a file is added.
  · PS4 WebKit reads the manifest entries as literal URLs: a backslash
    (`700\\alert.js`) is NOT a path separator — it 404s. This script can
    never emit one because it builds every entry with forward slashes.

Usage:  python3 tools/gen_manifests.py
Run from the repository root. Regenerates every host cache.manifest.
"""

import hashlib
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# dir -> (extra alias URLs the exploit code may request, docstring)
HOSTS = {
    "505": [],
    "672": [],
    "700": [],
    "900": [],
    "css": [],
    # chain_lapse.js / chain_poops.js / jb.js / mem.js all import
    # "./core.js?v=10" — the module-relative query string makes that a
    # distinct URL, so the cache must contain it verbatim.
    "slopkit": ["core.js?v=10"],
}

SHARED = ["../style.css", "../background.jpg"]
NAV_LABELS = {
    "505": "WebKit + BPF",
    "672": "jb",
    "700": "PSFree + Lapse",
    "900": "PSFree + Lapse",
    "css": "CSSFontFace",
    "slopkit": "SLOP",
}


def _sort_key(name):
    digits = "".join(c if c.isdigit() else "0" for c in os.path.basename(name))
    return (int(digits) if digits else 0, name)


def rev():
    try:
        sha = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout.strip()
        return sha or os.urandom(4).hex()
    except Exception:
        return os.urandom(4).hex()


def gen_manifest(host, aliases):
    files = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, host)):
        dirnames.sort()
        for fn in sorted(filenames):
            rel = os.path.relpath(os.path.join(dirpath, fn), os.path.join(ROOT, host))
            files.append(rel.replace(os.sep, "/"))
    files = [f for f in files if f != "cache.manifest"]
    files.sort(key=_sort_key)
    files += sorted(a for a in aliases if a not in files)
    files += SHARED
    # index.html / cache.html are real files too — dedupe, keep first order.
    seen = set()
    ordered = []
    for f in ["index.html", "cache.html"] + files:
        if f in seen:
            continue
        seen.add(f)
        if os.path.exists(os.path.join(ROOT, host, f)):
            ordered.append(f)
    files = ordered
    files.append("cache.manifest")

    lines = [
        "CACHE MANIFEST",
        "# rev " + rev() + " — generated by tools/gen_manifests.py, do not edit by hand",
        "# host: " + host + " (" + NAV_LABELS[host] + ") — forward slashes only:",
        "# a manifest entry with a backslash would 404 and kill the install",
        "",
        "CACHE:",
    ]
    lines += files
    lines += ["", "NETWORK:", "*"]
    out = "\n".join(lines) + "\n"
    path = os.path.join(ROOT, host, "cache.manifest")
    with open(path, "w", newline="\n") as fh:
        fh.write(out)
    print("%-8s %d entries" % (host, len([l for l in lines if l not in ("CACHE:", "NETWORK:", "*", "")]))) 

    # Sanity check: every entry must resolve to a real file.
    missing = []
    for entry in lines:
        if entry.startswith(("CACHE", "NETWORK", "#", "") ) or entry == "*":
            continue
        target = os.path.normpath(os.path.join(ROOT, host, entry))
        if not os.path.exists(target):
            missing.append(entry)
    if missing:
        print("ERROR: unresolved manifest entries in %s: %s" % (path, missing))
        sys.exit(1)


def main():
    if not os.path.isdir(ROOT):
        sys.exit("bad root")
    for host, aliases in HOSTS.items():
        gen_manifest(host, aliases)
    print("ok")


if __name__ == "__main__":
    main()
